def channel_totals():
    """返回 {渠道: (曝光量, 线索数量, 有效线索, 转化率%)}"""
    out = {}
    for ch in CHANNELS:
        rows = CHANNEL_WEEKLY[ch]
        exp = sum(r[1] for r in rows)
        lead = sum(r[2] for r in rows)
        qual = sum(r[3] for r in rows)
        out[ch] = (exp, lead, qual, round(qual / lead * 100, 1))
    return out


def grand_total():
    """返回 (总曝光, 总线索, 总有效线索, 整体转化率%)"""
    t = channel_totals()
    exp = sum(v[0] for v in t.values())
    lead = sum(v[1] for v in t.values())
    qual = sum(v[2] for v in t.values())
    return exp, lead, qual, round(qual / lead * 100, 1)


