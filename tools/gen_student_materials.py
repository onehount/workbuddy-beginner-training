def gen_task_cards():
    paths = []
    for card in CARDS:
        lines = [
            f"# {card['id']} · {card['title']}",
            "",
            f"> 提示词参考：`06-prompts/{card['prompt_ref']}`",
            "",
            "| 属性 | 内容 |",
            "|------|------|",
            f"| **输入** | {card['input']} |",
            f"| **输出** | {card['output']} |",
            "",
            "## 操作步骤",
            "",
        ]
        for i, step in enumerate(card["steps"], 1):
            lines.append(f"{i}. {step}")
            lines.append("")
        lines.extend([
            "## 要点",
            "",
        ])
        for p in card["key_points"]:
            lines.append(f"- {p}")
            lines.append("")
        lines.extend([
            "## 常见错误",
            "",
        ])
        for e in card["common_errors"]:
            lines.append(f"- ⚠️ {e}")
            lines.append("")
        lines.append("---")
        lines.append(f"*{C.BRAND_CN} 教学案例 · Agent 任务卡*")

        path = os.path.join(AT, f"{card['id']}_{card['title'].replace(' ','_')}.md")
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        paths.append(path)
    return paths


